"""Small DB-API adapter for the application's fixed SQL statements."""
import os
from pathlib import Path
import re
import sqlite3
from contextlib import contextmanager


def postgres_enabled():
    backend = os.environ.get('MARKET_DATABASE', 'sqlite')
    if backend not in ('sqlite', 'postgres'):
        raise RuntimeError('MARKET_DATABASE deve ser sqlite ou postgres.')
    return backend == 'postgres'


class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


class Cursor:
    def __init__(self, cursor, generated=False):
        self.cursor = cursor
        self.rowcount = cursor.rowcount
        self.lastrowid = cursor.fetchone()['id'] if generated else None

    def fetchone(self):
        row = self.cursor.fetchone()
        return Row(row) if row is not None else None

    def fetchall(self):
        return [Row(row) for row in self.cursor.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


class Postgres:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=()):
        import psycopg
        # Only application-owned SQL is adapted; values stay bound parameters.
        if query.strip().upper() == 'BEGIN IMMEDIATE':
            # Serialize purchase creation, matching SQLite's write transaction.
            return Cursor(self.connection.execute('SELECT pg_advisory_xact_lock(7241901)'))
        query = query.replace('?', '%s')
        if query.lstrip().upper().startswith('INSERT OR IGNORE INTO'):
            query = query.replace('INSERT OR IGNORE INTO', 'INSERT INTO', 1) + ' ON CONFLICT DO NOTHING'
        generated = bool(re.match(r'\s*INSERT INTO (users|orders|events|listings|purchases)\b', query, re.I))
        if generated:
            query += ' RETURNING id'
        try:
            # Savepoint permits a handled duplicate email without aborting the transaction.
            with self.connection.transaction():
                cursor = self.connection.execute(query, params)
                if generated and cursor.rowcount == 0:
                    generated = False
                return Cursor(cursor, generated)
        except psycopg.IntegrityError as error:
            raise sqlite3.IntegrityError('Restrição de integridade do banco.') from error

    def executescript(self, script):
        script = re.sub(r'\bid INTEGER PRIMARY KEY\b', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', script)
        script = re.sub(r'\bBLOB\b', 'BYTEA', script)
        script = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', script)
        script = script.replace('DEFAULT CURRENT_TIMESTAMP', 'DEFAULT (CURRENT_TIMESTAMP::text)')
        for statement in script.split(';'):
            if statement.strip():
                self.connection.execute(statement)

    def sync_identity(self, table):
        if table not in ('users', 'orders', 'events', 'listings', 'purchases'):
            raise ValueError('Tabela inválida.')
        self.connection.execute(
            f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), COALESCE(MAX(id),1), MAX(id) IS NOT NULL) FROM {table}")


@contextmanager
def connect_postgres():
    import psycopg
    from psycopg.rows import dict_row
    password_file = os.environ.get('PGPASSWORD_FILE')
    kwargs = {'connect_timeout': 10, 'row_factory': dict_row,
              'options': '-c statement_timeout=15000 -c lock_timeout=10000'}
    if password_file:
        kwargs['password'] = Path(password_file).read_text().strip()
    with psycopg.connect(**kwargs) as connection:
        connection.execute('BEGIN')
        schema = os.environ.get('MARKET_PG_SCHEMA', 'public')
        connection.execute(psycopg.sql.SQL('SET LOCAL search_path TO {}').format(psycopg.sql.Identifier(schema)))
        yield Postgres(connection)
